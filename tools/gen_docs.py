"""Generate data-driven docs from out/*.json|csv: docs/PRINT_GUIDE.md, docs/ANALYSIS.md. Run after `make all`."""
import csv, json, os
ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..")
O = lambda *p: os.path.join(ROOT, "out", *p)

def print_guide():
    rows = list(csv.DictReader(open(O("print_plan.csv"))))
    tot = sum(float(r["mass_g"]) for r in rows); hrs = sum(float(r["est_print_h"]) for r in rows)
    L = ["# Print guide", "",
         f"{len(rows)} printed parts (including the 2 TPU soles). Net model mass **{tot:.0f} g**, estimated **{hrs:.0f} h** of printing (very rough: mass / 12 g/h + 0.3 h per part).",
         "Ready-to-slice STLs (already rotated to a stable face-down pose, origin at the bed corner): `out/stl_print/`. STEP: `out/step/`.", "",
         "## Material and settings", "",
         "| Group | Material | Nozzle / layer | Walls | Infill | Notes |", "|---|---|---|--:|--:|---|",
         "| Links, pelvis, torso (PETG-CF) | PETG-CF (or PA-CF) | 0.4 / 0.2 | 4 | 40 % gyroid | Dry the filament. Print bars flat (as oriented) so layers run along the bar. Do not use PLA: servo cradles get warm. |",
         "| Head, covers, Pi tray (PETG) | PETG | 0.4 / 0.2 | 3 | 20 % | |",
         "| Foot soles (TPU 95A) | TPU 95A | 0.4 / 0.2 | 3 | 100 % | 20 mm/s, no retraction tuning needed on direct drive |", "",
         "After printing: ream every servo pocket and 3.4 mm hole with the matching drill by hand; the pockets are 0.3 mm oversize (see `CLEAR` in `cad/params.py`). Tune `CLEAR` for your printer, re-run `make export`.", "",
         "## Part list", "", "| Part | Material | Qty | Mass g | Size mm | Est. h |", "|---|---|--:|--:|---|--:|"]
    for r in rows: L.append(f"| {r['part']} | {r['material']} | {r['qty']} | {r['mass_g']} | {r['size_mm']} | {r['est_print_h']} |")
    open(os.path.join(ROOT, "docs", "PRINT_GUIDE.md"), "w").write("\n".join(L) + "\n")

def analysis():
    t = json.load(open(O("torque_report.json"))); p = json.load(open(O("power_report.json"))); m = json.load(open(O("model.json")))
    mass = sum(x["mass"] for x in m["parts"]) / 1000
    byk = {}
    for x in m["parts"]: byk[x["kind"]] = byk.get(x["kind"], 0) + x["mass"]
    L = ["# Analysis results (auto-generated)", "", "Generated by `make analysis` from the CAD. Method and assumptions: see `docs/DESIGN.md`.", "",
         f"## Mass budget — **{mass:.2f} kg** total", "", "| Group | Mass g |", "|---|--:|"]
    names = {"servo": "20 servos", "printed": "printed parts", "elec": "electronics + battery + camera", "misc": "wiring / fasteners allowance"}
    for k, v in sorted(byk.items(), key=lambda kv: -kv[1]): L.append(f"| {names.get(k, k)} | {v:.0f} |")
    L += ["", "## Joint torque envelope (static, representative poses × 1.8 dynamic factor)", "",
          "Criterion: peak = static × 1.8 must be ≤ 65 % of servo stall torque. Servo ratings: STS3215 stall 2.9 N·m / rated 1.0; STS3250 stall 4.9 / rated 1.6.", "",
          "| Joint | Servo | Static N·m | Peak N·m | % of stall | Static vs rated | OK |", "|---|---|--:|--:|--:|--:|---|"]
    for r in t["envelope"]:
        L.append(f"| {r['joint']} | {r['servo']} | {r['static_nm']:.2f} | {r['peak_nm']:.2f} | {100*r['peak_over_stall']:.0f} % | {r['static_over_rated']:.2f}× | {'yes' if r['ok'] else '**NO**'} |")
    L += ["", "Cases evaluated (single-support squat with lateral lean, CoP shifts ±30 mm/±20 mm, double-support squats to 55°, swing leg, arm reach with 200 g payload, neck):", ""]
    for k, c in t["cases"].items():
        L.append(f"- `{k}`: " + ("CoM inside foot, margin %.0f mm" % c["x_margin_mm"] if "x_margin_mm" in c else "free-space load") + " — " + ", ".join(f"{a} {b:.2f}" for a, b in c["tau"].items()))
    L += ["", "## Power and runtime (from the MuJoCo walking run)", "",
          f"- Mean servo current while walking: **{p['servo_current_a']} A** at ~11.1 V → with {9} W compute: **{p['total_w']} W**",
          f"- 3S 3000 mAh pack, 85 % usable ({p['usable_wh']} Wh): about **{p['runtime_min_walking']:.0f} min** of walking",
          f"- Sum of per-joint peak currents seen in the walk: {p['sum_of_joint_peaks_a']} A (never simultaneous) → 20 A fuse. All servos stalled: {p['stall_all_a']} A (protected by torque limit + fuse).", ""]
    open(os.path.join(ROOT, "docs", "ANALYSIS.md"), "w").write("\n".join(L) + "\n")

def assembly_table():
    m = json.load(open(O("model.json"))); cfg = json.load(open(os.path.join(ROOT, "firmware", "config", "joints.json")))
    holder = lambda j: {"base": None}.get(j["parent"], "link_" + j["parent"])
    def sits(n, j):
        if n == "neck_pitch": return "`head_shell` (servo body moves with the head)"
        if n == "neck_yaw": return "`torso_shell` (top plate)"
        if j["parent"] == "base": return "`pelvis`" if "hip" in n else "`torso_shell` (side wall)"
        return f"`link_{j['parent']}`"
    L = ["# Joint / part assembly table (auto-generated)", "",
         "Each joint is one servo. The **servo body** sits in a printed cradle; the servo **horn** carries the next printed link, bolted with 4×M3 + 1 centre M3.",
         "Servo IDs are fixed here - label cables and servos before assembly.", "",
         "| # | Joint | Servo | Bus | Axis | Range (body°) | Servo body sits in | Horn drives |", "|--:|---|---|---|---|---|---|---|"]
    for n, c in sorted(cfg.items(), key=lambda kv: kv[1]["id"]):
        j = m["joints"][n]; lo, hi = sorted((c["sign"] * j["lo"], c["sign"] * j["hi"]))
        drives = "`neck_fork`" if n == "neck_yaw" else ("`neck_fork` (head turns on it)" if n == "neck_pitch" else f"`link_{n}`")
        L.append(f"| {c['id']} | {n} | {c['servo']} | {c['bus']} | {c['axis']} | {lo:.0f} … {hi:.0f} | {sits(n, j)} | {drives} |")
    counts = {}
    for c in cfg.values(): counts[c["servo"]] = counts.get(c["servo"], 0) + 1
    L += ["", "Servo count: " + ", ".join(f"{v}× {k}" for k, v in counts.items()) + " (+1 spare STS3215 in the BOM).", ""]
    open(os.path.join(ROOT, "docs", "ASSEMBLY_TABLE.md"), "w").write("\n".join(L) + "\n")

def harness():
    m = json.load(open(O("model.json"))); J = m["joints"]
    import math
    chains = {"Bus A - left leg": ["L_hip_yaw", "L_hip_roll", "L_hip_pitch", "L_knee", "L_ankle_pitch", "L_ankle_roll"],
              "Bus A - right leg": ["R_hip_yaw", "R_hip_roll", "R_hip_pitch", "R_knee", "R_ankle_pitch", "R_ankle_roll"],
              "Bus B - left arm": ["L_sh_pitch", "L_sh_roll", "L_elbow"], "Bus B - right arm": ["R_sh_pitch", "R_sh_roll", "R_elbow"], "Bus B - neck": ["neck_yaw", "neck_pitch"]}
    hub = {"Bus A - left leg": (0, 50, 400), "Bus A - right leg": (0, -50, 400), "Bus B - left arm": (0, 40, 480), "Bus B - right arm": (0, -40, 480), "Bus B - neck": (0, 0, 480)}
    L = ["# Servo cable lengths (auto-generated from CAD)", "", "Straight-line distance between consecutive servos + 40 mm routing slack, rounded up to the next stock length (100/150/200/300 mm). First hop starts at the torso hub (assumed at the pelvis/torso floor).", "",
         "| Chain | Hop | Straight mm | Cable to buy mm |", "|---|---|--:|--:|"]
    stock = [100, 150, 200, 300, 400]
    for ch, names in chains.items():
        prev = hub[ch]
        for n in names:
            p = J[n]["pos"]; d = math.dist(prev, p) + 40
            L.append(f"| {ch} | -> {n} | {math.dist(prev, p):.0f} | {next((s for s in stock if s >= d), 500)} |"); prev = p
    open(os.path.join(ROOT, "docs", "HARNESS.md"), "w").write("\n".join(L) + "\n")

if __name__ == "__main__":
    print_guide(); analysis(); assembly_table(); harness(); print("docs generated")
